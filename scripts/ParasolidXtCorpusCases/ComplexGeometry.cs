static unsafe PK_BODY_t CreateBCurve()
{
    var vertices = stackalloc double[]
    {
        0.0, 0.0, 0.0,
        1.0, 2.0, 0.5,
        2.0, -1.0, 1.0,
        4.0, 0.0, 0.0,
    };
    var knotMultiplicities = stackalloc int[] { 4, 4 };
    var knots = stackalloc double[] { 0.0, 1.0 };
    var standardForm = new PK_BCURVE_sf_t(
        3,
        4,
        3,
        PK_LOGICAL_false,
        vertices,
        PK_BCURVE_form_arbitrary_c,
        2,
        knotMultiplicities,
        knots,
        PK_knot_non_uniform_c,
        PK_LOGICAL_false,
        PK_LOGICAL_false,
        PK_self_intersect_false_c);
    PK_BCURVE_t bcurve;
    ParasolidXtCorpusHost.Check(PK_BCURVE_create(&standardForm, &bcurve), "PK_BCURVE_create");
    return AddConstructionGeometry(bcurve);
}

