static unsafe PK_BODY_t CreateSPCurve()
{
    var planeForm = new PK_PLANE_sf_t(new PK_AXIS2_sf_t(
        new PK_VECTOR_t(0.0, 0.0, 0.0),
        new PK_VECTOR1_t(0.0, 0.0, 1.0),
        new PK_VECTOR1_t(1.0, 0.0, 0.0)));
    PK_PLANE_t plane;
    ParasolidXtCorpusHost.Check(PK_PLANE_create(&planeForm, &plane), "PK_PLANE_create for spcurve");
    var lineForm = new PK_LINE_sf_t(new PK_AXIS1_sf_t(
        new PK_VECTOR_t(-1.5, 0.0, 0.0),
        new PK_VECTOR1_t(1.0, 0.0, 0.0)));
    PK_LINE_t line;
    ParasolidXtCorpusHost.Check(PK_LINE_create(&lineForm, &line), "PK_LINE_create for spcurve");

    var options = new PK_CURVE_make_spcurves_o_t();
    int count;
    PK_SPCURVE_t* spcurves;
    ParasolidXtCorpusHost.Check(
        PK_CURVE_make_spcurves_2(line, new PK_INTERVAL_t(-1.5, 1.5), plane, 1.0e-5, &options, &count, &spcurves),
        "PK_CURVE_make_spcurves_2");
    try
    {
        if (count != 1)
            throw new InvalidOperationException("expected one SP-curve, got " + count);
        return AddConstructionGeometry(spcurves[0]);
    }
    finally
    {
        if (spcurves is not null)
            ParasolidXtCorpusHost.Check(PK_MEMORY_free(spcurves), "PK_MEMORY_free spcurves");
    }
}

